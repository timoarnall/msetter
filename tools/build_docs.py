# ---------- reading the app's files ----------

def read(path):
    with open(os.path.join(ROOT, path), encoding='utf-8') as f:
        return f.read()

def fail(msg):
    sys.exit('build_docs: ' + msg)

def js_str(s):
    return re.sub(r"\\(.)", r'\1', s)

STR = r"'((?:[^'\\]|\\.)*)'"

def js_object(text, name):
    """The text between the braces of `var NAME = { ... };` (top level only)."""
    m = re.search(r'var ' + name + r' = \{', text)
    if not m:
        fail('could not find var ' + name)
    i, depth = m.end(), 1
    while depth:
        c = text[i]
        if c == '{': depth += 1
        elif c == '}': depth -= 1
        elif c == "'":
            i = text.index("'", i + 1)
            while text[i - 1] == '\\': i = text.index("'", i + 1)
        i += 1
    return text[m.end():i - 1]

def load_rules():
    m = re.search(r'var RULES = (\{.*\});\s*\n', read('src/rules.js'), re.S)
    if not m:
        fail('could not read src/rules.js')
    return json.loads(m.group(1))

def load_catalogue():
    text = read('src/catalogue.js')
    themes = []
    starts = list(re.finditer(r"\{ id: '(\w+)', title: " + STR, text))
    if not starts:
        fail('no themes found in src/catalogue.js')
    end = text.index('var LAYOUTS')
    for n, t in enumerate(starts):
        stop = starts[n + 1].start() if n + 1 < len(starts) else end
        rows_at = text.find('rows: [', t.end(), stop)
        chunk = text[rows_at:stop] if rows_at >= 0 else ''
        rows = []
        for line in chunk.splitlines():
            code = re.search(r"\bcode: '([0-9A-F]{4})'", line)
            style = re.search(r'\bcodeFor: styleCode\((\d)\)', line)
            if not code and not style:
                continue
            name = re.search(r'\bname: ' + STR, line)
            help_ = re.search(r'\bhelp: ' + STR, line)
            only = re.search(r'\bonly: \[([^\]]*)\]', line)
            if not name:
                fail('a row in src/catalogue.js has no name: ' + line.strip())
            rows.append({
                'code': code.group(1) if code else None,
                'style': int(style.group(1)) if style else None,
                'name': js_str(name.group(1)),
                'help': js_str(help_.group(1)) if help_ else '',
                'only': re.findall(STR, only.group(1)) if only else None,
            })
        themes.append({'id': t.group(1), 'title': js_str(t.group(2)), 'rows': rows})

    style = {}
    for k, v in re.findall(r'(\d+): \[([^\]]*)\]', js_object(text, 'STYLE')):
        style[int(k)] = [None if x == 'null' else x.strip("'") for x in re.findall(r"'\w{4}'|null", v)]

    layouts = []
    m = re.search(r'var LAYOUTS = \[(.*?)\];', text, re.S)
    for obj in re.findall(r'\{([^}]*)\}', m.group(1)):
        layouts.append(dict(re.findall(r"(\w+): '([0-9A-F]{4})'", obj)))

    lens = dict((k, js_str(v)) for k, v in re.findall(r'(\w+): ' + STR, js_object(text, 'LENS_SPEED')))
    option_help = {}
    oh = js_object(text, 'OPTION_HELP')
    for code, body in re.findall(r"'?([0-9A-F]{4})'?: \{(.*?)\}", oh, re.S):
        d = {}
        for v, s, ref in re.findall(r'(-?\d+): (?:' + STR + r'|LENS_SPEED\.(\w+))', body):
            d[int(v)] = js_str(s) if s else lens[ref]
        option_help[code] = d

    # JOB_HELP is declared twice in catalogue.js: once as a string, then as the object of job help.
    m = re.search(r'var JOB_HELP = \{', text)
    job_help_text = js_object(text[m.start():], 'JOB_HELP')
    job_help = dict((int(k), js_str(v)) for k, v in re.findall(r'(\d+): ' + STR, job_help_text))
    job_codes = re.findall(r'([0-9A-F]{4}): 1', js_object(text, 'JOB_CODES'))
    job_setting = dict((int(k), v) for k, v in re.findall(r"(\d+): '([0-9A-F]{4})'", js_object(text, 'JOB_SETTING')))
    fav_setting = dict((int(k), v) for k, v in re.findall(r"(\d+): '([0-9A-F]{4})'", js_object(text, 'FAVORITE_SETTING')))

    if not job_help or not job_setting or len(layouts) != 4:
        fail('src/catalogue.js has changed shape; update load_catalogue()')
    return {'themes': themes, 'style': style, 'layouts': layouts, 'option_help': option_help,
            'job_help': job_help, 'job_codes': job_codes, 'job_setting': job_setting, 'fav_setting': fav_setting}

def load_engine():
    text = read('src/engine.js')
    fav_max = re.search(r'var FAVORITES_MAX = (\d+);', text)
    items = {}
    m = re.search(r'var FACTORY_ITEMS = \{([^}]*)\}', text)
    if m:
        for code, lst in re.findall(r'([0-9A-F]{4}): \[([^\]]*)\]', m.group(1)):
            items[code] = [int(x) for x in re.findall(r'-?\d+', lst)]
    return {'fav_max': int(fav_max.group(1)) if fav_max else 11, 'factory_items': items}


