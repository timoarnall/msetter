def merge_orders(lists):
    """One order that keeps every list's own order (the camera's file order, or a menu's option order)."""
    out = []
    for lst in lists:
        prev = None
        for x in lst:
            if x not in out:
                out.insert(out.index(prev) + 1 if prev is not None else 0, x)
            prev = x
    return out

ORDER = merge_orders([RULES['models'][m]['order'] for m in MODELS])
ALL = set(ORDER)

def cams_with(code):
    return [m for m in MODELS if code in R[m]]

def any_rule(code):
    return R[cams_with(code)[0]][code]

