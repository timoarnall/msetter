# ---------- formatting ----------

def esc(s):
    return str(s).replace('|', '\\|').replace('<', '&lt;').replace('>', '&gt;')

def fmt(code, v):
    if isinstance(v, str):
        return '"%s"' % v if v else '"" (empty)'
    n = label(code, v)
    if n is not None:
        return str(v) if n == str(v) else '%s (%s)' % (v, esc(n))
    if code in RULES['labels']:
        return '%s (no name yet)' % v
    return str(v)

def factory(m, code):
    r = R[m][code]
    if r.get('dyn'):
        items = [i for i in ENG['factory_items'].get(code, []) if i in r['v']]
        return (r['d'], tuple(items))
    return r['d']

def fmt_factory(code, f):
    if isinstance(f, tuple):
        v, items = f
        if not items:
            return '%s, no items' % v
        return '%s, items %s' % (v, ', '.join(fmt(code, i) for i in items))
    return fmt(code, f)

def join_names(ms, word='and'):
    ms = list(ms)
    if len(ms) == 1:
        return 'the ' + ms[0]
    return 'the ' + ', '.join(ms[:-1]) + ' ' + word + ' ' + ms[-1]

def cameras_line(code):
    have = cams_with(code)
    if len(have) == len(MODELS):
        return 'all'
    lack = [m for m in MODELS if m not in have]
    if len(have) == 1:
        return 'only %s' % join_names(have)
    return '%s; not %s' % (join_names(have), join_names(lack, 'or'))

def kind_line(code):
    r = any_rule(code)
    if r.get('dyn'):
        kind = 'a value followed by a list of items'
    elif r['k'] == 'l':
        kind = 'one of a list of numbers' if len(r['v']) > 1 else 'a single allowed number'
    elif r['k'] == 'r':
        lo = min(R[m][code]['min'] for m in cams_with(code)); hi = max(R[m][code]['max'] for m in cams_with(code))
        kind = 'a whole number from %s to %s' % (lo, hi)
    else:
        kind = ('text of exactly %d characters' % r['min']) if r['min'] == r['max'] else ('text of %d to %d characters' % (r['min'], r['max']))
    return kind

def factory_line(code):
    groups = {}
    for m in cams_with(code):
        groups.setdefault(json.dumps(factory(m, code)), []).append(m)
    if len(groups) == 1:
        f = factory(cams_with(code)[0], code)
        return fmt_factory(code, f)
    parts = []
    for key, ms in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        f = factory(ms[0], code)
        parts.append('%s on %s' % (fmt_factory(code, f), join_names(ms)))
    return '; '.join(parts)

def all_values(code):
    return merge_orders([R[m][code]['v'] for m in cams_with(code) if R[m][code]['k'] == 'l'])

def option_help(code, v):
    if code in CAT['job_codes']:
        return CAT['job_help'].get(v, '')
    return CAT['option_help'].get(code, {}).get(v, '')

def page_of(code):
    return PAGE_OF.get(code, 'other')

def link(code, here=None):
    p = page_of(code)
    return '[%s](%s#%s)' % (code, '' if p == here else p + '.md', code.lower())

def values_table(code, here):
    r = any_rule(code)
    if r['k'] != 'l':
        return []
    vals = all_values(code)
    have = cams_with(code)
    differs = any(v not in R[m][code]['v'] for m in have for v in vals)
    helps = [option_help(code, v) for v in vals]
    fav = code == 'D1A9'
    if not differs and not any(helps) and all(label(code, v) is None for v in vals):
        return ['Allowed %s: %s. No names known yet.' % ('value' if len(vals) == 1 else 'values', ', '.join(str(v) for v in vals))]
    head = ['Value', 'Camera\'s name']
    if fav: head.append('Setting it shows')
    if any(helps): head.append('What it does')
    if differs: head.append('Not on')
    rows = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    for v, h in zip(vals, helps):
        n = label(code, v)
        cells = [str(v), esc(n) if n is not None else 'No name yet']
        if fav:
            s = CAT['fav_setting'].get(v) or ('%04X' % v if v > 255 else None)
            cells.append(link(s, here) if s and s in ALL else ((s + ', not in the file') if s else ''))
        if any(helps): cells.append(esc(h))
        if differs: cells.append(', '.join(m for m in have if v not in R[m][code]['v']))
        rows.append('| ' + ' | '.join(cells) + ' |')
    return rows

def entry(code, here):
    out = ['### %s' % code, '', '**%s**' % esc(name_of(code))]
    if code in PLAIN:
        n, h, _, only = PLAIN[code]
        out += ['', 'Msetter: %s.%s' % (esc(n), (' ' + esc(h)) if h else '')]
    scope = 'per profile, seven slots' if any_rule(code)['p'] else 'camera-wide, one slot'
    out += ['', '- Scope: ' + scope, '- Kind: ' + kind_line(code), '- Factory value: ' + factory_line(code), '- Cameras: ' + cameras_line(code)]
    if code in NOTES:
        out += ['', NOTES[code]]
    t = values_table(code, here)
    if t:
        out += [''] + t
    return out + ['']


