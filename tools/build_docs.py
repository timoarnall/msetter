def layout_matrix():
    rows = ['| | ' + ' | '.join('Layout %d' % (i + 1) for i in range(len(CAT['layouts']))) + ' |',
            '|---|' + '---|' * len(CAT['layouts'])]
    for key, nm in LAYOUT_NAMES.items():
        cells = []
        for L in CAT['layouts']:
            c = L.get(key)
            if not c or c not in ALL:
                cells.append('')
                continue
            fs = {}
            for m in cams_with(c):
                fs.setdefault(json.dumps(factory(m, c)), []).append(m)
            if len(fs) == 1:
                f = fmt_factory(c, factory(cams_with(c)[0], c))
            else:
                main = max(fs.values(), key=len)
                f = fmt_factory(c, factory(main[0], c)) + '; ' + '; '.join(
                    fmt_factory(c, factory(ms[0], c)) + ' on ' + ', '.join(ms) for ms in fs.values() if ms is not main)
            cells.append('[%s](#%s) %s' % (c, c.lower(), f))
        rows.append('| %s | %s |' % (nm, ' | '.join(cells)))
    return rows

