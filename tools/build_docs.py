# Build the settings reference in docs/settings/ from the app's own data.
#
# Usage: python3 tools/build_docs.py
#
# Reads:
#   src/rules.js      every camera's codes, file order, kinds, allowed values, factory values and the camera's names
#   src/catalogue.js  Msetter's plain names, one-line help, themes, screen layouts, button job help
#   src/engine.js     the Favorites item a reset camera holds, the Favorites limit
# Writes every page in docs/settings/ and removes generated pages that are no longer made.
# Hand-written pages (docs/*.md) are never touched.
#
# Standard library only. When src/ changes, run this again and commit the result with it.
#
# To extend:
#   - A new camera or a new code in rules.js needs nothing here; it shows up on its own. A code that no page
#     claims lands on "Other settings" with a warning; give it a page in PAGES below.
#   - NOTES holds short facts the app does not carry (how a number is written, what a manual says, what is
#     not yet confirmed). Keep each one to a sentence or two. Mark anything not seen on a real camera with
#     NOT_CONFIRMED so it can be found with grep.
